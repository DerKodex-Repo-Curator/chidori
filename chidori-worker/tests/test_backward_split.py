import torch, torch.nn as nn
torch._C._cuda_init()
print("Devices:", torch.cuda.device_count())
embed = nn.Embedding(5000, 512).cuda(0)
l1 = nn.Linear(512, 1024).cuda(0)
l2 = nn.Linear(1024, 1024).cuda(1)
l3 = nn.Linear(1024, 512).cuda(1)
head = nn.Linear(512, 5000).cuda(0)
print("Layers built")
x = torch.randint(0, 5000, (32, 32))
h = embed(x.cuda(0))
h = torch.relu(l1(h))
print("Local forward OK")
h = h.cuda(1)
h = torch.relu(l2(h))
h = torch.relu(l3(h))
print("Remote forward OK")
h = h.cuda(0)
logits = head(h)
print("Head OK")
loss = nn.CrossEntropyLoss()(logits.reshape(-1, 5000), x.cuda(0).reshape(-1))
print(f"Loss: {loss.item()}")
print("About to backward...")
loss.backward()
print("BACKWARD OK")
